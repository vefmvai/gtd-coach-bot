"""Ночная проверка памяти: не пора ли её обновить и где она за день подвела.

Зачем это вообще. Разбор сессии 31.07 нашёл протечку: коуч каждый день
пользовался наблюдением «ставка на кон заводит», а в модуле знаний его не было
вовсе — оно жило только в выжимках, то есть в окне, которое уезжает вперёд.
Причина не в лени модели, а в разнице механизмов: выжимку пишет код по
будильнику и она случается всегда, а запись в `знания/` держалась на просьбе
в тексте конституции — «увидел паттерн, допиши» — и случалась через раз.

Лекарство ровно одно: повесить проверку памяти на тот же будильник. Ночью,
сразу после выжимки, день перечитывается второй раз — но другими глазами:
не «что произошло», а «что из этого должно осесть в памяти и где память
сегодня не сработала».

Две вещи, которые здесь НЕ делаются намеренно:

1. **Ничего не пишется в `знания/` молча.** Граница из PROJECT.md: факт сказал
   человек — пишется сразу; вывод придумал бот — только после подтверждения.
   Ночью бот человека не спросит, поэтому ночь только предлагает. Записывает
   коуч в разговоре, когда пользователь подтвердил.
2. **Бот не оценивает сам себя.** Исходная идея была «пусть ночью оценивает,
   насколько адекватны критерии выжимки». Так не работает: оценивать нечем —
   он не знает, что выпало, потому что выпавшего у него уже нет. Поэтому мерим
   не самооценку, а **промахи** — наблюдаемые события: полез в архив за тем,
   что должно было быть в выжимке; переспросил то, что пользователь уже говорил.
   Через месяц это список улик, по которому критерии меняет человек
   правкой плагина, а не бот у себя в голове.

Найденное ложится на **полку входящих** (`inbox.py`), а не в markdown-копилки
мозга — так с 05.08.2026, этап 20. Разбор перестал зависеть от того, вспомнил ли
человек зачеркнуть строку.
"""

from __future__ import annotations

import logging
import re
from datetime import date
from pathlib import Path


from .backrun import прогон
from .inbox import ПРЕДЛОЖЕНИЕ, ПРОМАХ, Inbox
from .prompts import load as load_prompt

log = logging.getLogger(__name__)


class MemoryWatch:
    """Второй ночной вопрос к прожитому дню — про саму память."""

    def __init__(self, brain_dir: Path, inbox: Inbox, model: str = "claude-fable-5",
                 mode=None, cost=None) -> None:
        self.brain_dir = brain_dir
        # Находки ложатся на полку входящих, а не в markdown-копилки мозга
        # (этап 20, 05.08.2026). Отметка «разобрано» перестала быть зачёркиванием
        # строки: её ставит статус, и забыть его нельзя.
        self.inbox = inbox
        self.model = model
        # Фоновый режим. Проверка памяти ЧИТАЕТ знания, но читает их не сама —
        # текст подкладывается в промпт кодом, поэтому встроенные инструменты
        # ей не нужны, а правила записи не нужны тем более: она предлагает,
        # а записывает потом коуч в разговоре.
        self.mode = mode
        self.cost = cost

    async def _ask(self, prompt: str, system: str) -> str:
        return await прогон(
            mode=self.mode, prompt=prompt, system=system, model=self.model,
            effort="high",  # раз в сутки — экономить нечего
            cost=self.cost, channel="проверка памяти", что="проверка памяти",
        )

    def _knowledge(self) -> str:
        """Что коуч знает про пользователя сегодня — чтобы не предлагать записанное."""
        parts = []
        for folder in ("знания", "состояние"):
            for path in sorted((self.brain_dir / "память" / folder).glob("*.md")):
                parts.append(f"--- {folder}/{path.name} ---\n{path.read_text(encoding='utf-8')}")
        return "\n\n".join(parts)

    # Отказ модели: «нет» в начале строки, дальше может тянуться объяснение,
    # почему память сегодня молодец. Разбор 19.08.2026 нашёл, что за пять ночей
    # шесть записей из семи оказались такими отписками: сравнение было точным
    # (`body.lower() != "нет"`), а модель писала «нет. Наоборот: память
    # отработала — …» — и вся отписка ехала на полку как промах.
    ОТКАЗ = re.compile(r"^нет\b\s*[.,:;—–-]*\s*", re.IGNORECASE)

    # Отказ в хвосте. Разбор 31.10.2026, промах #328: на полку приехала строка
    # «В остальном — нет» — модель перечислила промахи и закрыла раздел
    # отпиской, которая начинается не с «нет», а кончается им. Узнаётся по двум
    # признакам сразу: кончается отказом и короткая. У настоящей находки есть
    # «что искали и где должно было лежать» — это всегда больше пяти слов,
    # поэтому «…а в памяти такого правила нет» остаётся находкой.
    ХВОСТ_ОТКАЗА = re.compile(r"(?:\bнет|\bне было|\bне нашлось|\bничего)\s*[.!…]*$", re.IGNORECASE)
    СЛОВ_У_ОТПИСКИ = 5

    @classmethod
    def отписка(cls, body: str) -> bool:
        if cls.ОТКАЗ.match(body):
            return True
        return bool(cls.ХВОСТ_ОТКАЗА.search(body)) and len(re.findall(r"\w+", body)) <= cls.СЛОВ_У_ОТПИСКИ

    @classmethod
    def _section(cls, answer: str, name: str) -> list[str]:
        """Достать раздел ответа. Разбор нарочно тупой: модель отвечает по форме."""
        lines = []
        inside = False
        for line in answer.splitlines():
            head = line.strip().rstrip(":").upper()
            if head in ("ФАКТЫ", "ВЫВОДЫ", "ПРОМАХИ"):
                inside = head == name
                continue
            if inside and line.strip().startswith("-"):
                body = line.strip()[1:].strip()
                if body and not cls.отписка(body):
                    lines.append(body)
        return lines

    async def run(self, day: date, transcript: str) -> dict[str, int]:
        """Перечитать день глазами памяти. Возвращает, сколько чего нашлось."""
        if len(transcript) < 200:
            return {"факты": 0, "выводы": 0, "промахи": 0}

        prompt = load_prompt("проверка-памяти")
        answer = await self._ask(
            prompt.format(day=day.isoformat(), knowledge=self._knowledge(), transcript=transcript),
            prompt.system,
        )
        facts = self._section(answer, "ФАКТЫ")
        conclusions = self._section(answer, "ВЫВОДЫ")
        misses = self._section(answer, "ПРОМАХИ")

        # Факт со слов человека и вывод коуча ложатся одним видом, а различает
        # их пометка в тексте. Граница «факт пишется сразу, вывод — только после
        # подтверждения» никуда не делась: её держит разговор, а не отдельная
        # полка. Две полки означали бы, что вывод, подтверждённый человеком,
        # обязан переехать между ними, — лишний ход и лишнее место для потери.
        for item in facts:
            self.inbox.положить(ПРЕДЛОЖЕНИЕ, item, день=day,
                                зачем="со слов пользователя — можно записывать сразу")
        for item in conclusions:
            self.inbox.положить(ПРЕДЛОЖЕНИЕ, item, день=day,
                                зачем="вывод коуча — сначала спросить пользователя")
        for item in misses:
            self.inbox.положить(ПРОМАХ, item, день=day)

        found = {"факты": len(facts), "выводы": len(conclusions), "промахи": len(misses)}
        log.info("ночная проверка памяти за %s: %s", day, found)
        return found

    def залежалось(self, сегодня: date) -> tuple[int, str]:
        """Что висит на полке входящих дольше нормы: сколько записей и с какого дня.

        **Считает все виды, а не одни предложения** (этап 20). Прежняя оговорка
        «промахи прибором не меряем, им положено копиться» снята вместе с причиной:
        у промаха теперь есть статус, и «копится» стало отличимо от «не разбирали».
        Заявки же не меряли вовсе — 18 строк без прибора, ровно та болезнь,
        которую проект ловит с 31.07.

        Считает сама полка — здесь только проводка: у прибора один дом.
        """
        return self.inbox.застой(сегодня)
