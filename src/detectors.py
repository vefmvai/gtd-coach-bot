def перегруз(задачи: list[dict], свободно: dict[str, float],
             дней: int = 7) -> list[Отклонение]:
    """Дни, куда набито больше, чем в них влезает.

    Свободные часы берутся из календаря: сутки — не мера, потому что три
    встречи по два часа съедают день, а список дел об этом не знает.
    Календарь молчит — считаем от рабочего дня и говорим, что считали так.
    """
    начало = _сегодня()
    по_дням: dict[date, list[dict]] = {}
    for задача in задачи:
        когда = _срок(задача)
        if когда and начало <= когда < начало + timedelta(days=дней):
            по_дням.setdefault(когда, []).append(задача)

    найдено = []
    for когда in sorted(по_дням):
        часов = _часы(по_дням[когда])
        если_бы = свободно.get(когда.isoformat())
        вместимость = если_бы if если_бы is not None else ДЕНЬ_ЧАСОВ
        if часов <= вместимость or not часов:
            continue
        откуда = "по календарю" if если_бы is not None else "рабочий день без календаря"
        найдено.append(Отклонение(
            "завал", "Перегруз дня",
            f"{когда.strftime('%d.%m')}: дел на {часов} ч, свободно {вместимость} ч "
            f"({откуда}), задач {len(по_дням[когда])}.",
        ))
    return найдено[:2]  # две худшие даты; остальное коуч спросит инструментом


def баланс_недели(задачи: list[dict], дней: int = 7) -> list[Отклонение]:
    """Всё свалено в один день при пустых соседних.

    Это не то же самое, что перегруз: день может влезать в норму и всё равно
    быть горкой рядом с двумя пустыми — и тогда лечится не отказом, а сдвигом.
    """
    начало = _сегодня()
    часы: dict[date, float] = {}
    for сдвиг in range(дней):
        когда = начало + timedelta(days=сдвиг)
        часы[когда] = _часы([з for з in задачи if _срок(з) == когда])
    if not any(часы.values()):
        return []
    горка = max(часы, key=lambda d: часы[d])
    ямы = [d for d, ч in часы.items() if ч == 0]
    if часы[горка] < 3 or len(ямы) < 2:
        return []
    return [Отклонение(
        "завал", "Баланс недели",
        f"Неделя перекошена: {горка.strftime('%d.%m')} — {часы[горка]} ч, "
        f"а {', '.join(d.strftime('%d.%m') for d in ямы[:3])} пусты.",
    )]


def мелочь(задачи: list[dict], сколько: int = 3) -> list[Отклонение]:
    """Дела на двадцать минут, которые можно закрыть заодно.

    Берём короткие без даты и просроченные короткие: они не всплывут сами,
    а закрываются между делом. Это единственный детектор, который не ругается,
    а предлагает лёгкое — он про то, чтобы день начался с движения.
    """
    сегодня = _сегодня()
    короткие = [
        з for з in задачи
        if "⏱️S" in (з.get("labels") or [])
        and (_срок(з) is None or _срок(з) < сегодня)
        and not з.get("parent_id")
    ]
    if not короткие:
        return []
    имена = ", ".join(f"«{з.get('content', '')}»" for з in короткие[:сколько])
    return [Отклонение(
        "мелочь", "Мелочь дня",
        f"На 20 минут, можно закрыть заодно ({len(короткие)} шт.): {имена}.",
    )]


def повторяющаяся(задача: dict) -> bool:
    """Задача с повтором («каждый месяц»). Её переносы ничего не значат."""
    return bool((задача.get("due") or {}).get("is_recurring"))


# Запись рабочей сессии в комментарии: «2026-08-04 — 3ч, сделано: …, дальше: …».
# Формат строгий именно затем, чтобы его читал код, а не человек глазами:
# по нему прибор отличает продолжение работы от уклонения. Тире принимаем любое
# (в телеграме прилетает и дефис, и длинное), часы — целые или с дробью.
#
# **Часы необязательны с 09.08.2026, и это починка, а не послабление.** Живая
# сверка нашла в аккаунте две записи, задуманные как сессии, и НИ ОДНА
# не разбиралась: «2026-08-06 — сессия работы (пришло вдохновение…)»,
# «2026-08-08 — большая сессия, сделано: …». Часов человек не назвал, а шаблон
# их требовал — то есть механизм, куплённый живым уроком 30.07–04.08, за три
# дня не сработал ни разу. Требовать было и незачем: число часов разборщик
# доставал и **выбрасывал**, дальше кода оно не шло никогда. Поэтому вторым
# куском принимается либо «Nч», либо само слово «сессия» рядом с тире.
# Шире не открываем: «2026-08-06 — перенёс на пятницу» сессией не является,
# и признать её таковой значило бы вернуть ровно ту слепоту, от которой
# всё затевалось.
СЕССИЯ = re.compile(
    r"^\s*(\d{4}-\d{2}-\d{2})\s*[-–—]\s*(?:\d+(?:[.,]\d+)?\s*ч|[^,\n]{0,12}сесси)",
    re.IGNORECASE,
)


def день_сессии(комментарий: str) -> date | None:
    """День рабочей сессии из комментария. Не запись сессии — None."""
    совпало = СЕССИЯ.match(комментарий or "")
    if not совпало:
        return None
    try:
        return date.fromisoformat(совпало.group(1))
    except ValueError:
        return None


async def свежие_сессии(client: TodoistClient, задачи: list[dict],
                        дней: int = 1, день: date | None = None) -> set[str]:
    """id задач, у которых есть запись рабочей сессии за вчера или сегодня.

    Комментарии тянем **только у кандидатов в хроники** — у тех, кто и так
    попал бы в отклонение. Их единицы (на живом аккаунте 06.08.2026 — семь),
    а тянуть комментарии ко всем ста сорока задачам значило бы сто сорок
    запросов ради вопроса, который стоит семи.

    Не ответил Todoist — считаем, что сессий нет: показать лишнее отклонение
    честнее, чем молча спрятать настоящее.
    """
    сегодня = день or _сегодня()
    рубеж = сегодня - timedelta(days=дней)
    кандидаты = [
        з for з in задачи
        if not повторяющаяся(з) and (з.get("postponed_count") or 0) >= ХРОНИКА
    ]
    найдено: set[str] = set()
    for з in кандидаты:
        try:
            данные = await client.get("/comments", params={"task_id": з["id"], "limit": 20})
        except TodoistError as err:
            log.warning("комментарии задачи %s не снялись: %s", з.get("id"), err)
            continue
        строки = данные.get("results", []) if isinstance(данные, dict) else (данные or [])
        for c in строки:
            когда = день_сессии(c.get("content") or "")
            if когда and когда >= рубеж:
                найдено.add(str(з["id"]))
                break
    if найдено:
        log.info("свежие рабочие сессии, переносы не в счёт: %d задач", len(найдено))
    return найдено


def хронические_переносы(задачи: list[dict], порог: int = ХРОНИКА,
                         сессии: set[str] | None = None) -> list[Отклонение]:
    """Задачи, которые переезжают снова и снова.

    Перенос — не лень, а признак: задача либо великовата, либо страшновата,
    либо не своя. Лечится дроблением или отказом, но сначала её надо увидеть.

    Считает сам Todoist — поле `postponed_count`. Мы собирались считать это
    по своим снимкам, но прогон 01.08 показал две вещи. Первая: поле живое
    и историческое — оно уже помнит, что «Ленэнерго» переезжало 26 раз,
    а свои снимки заговорили бы недели через две. Вторая: оно считает и то,
    что человек двигает пальцем в телефоне, а туда наш снимок не заглядывает.

    **Повторяющиеся исключаем, и это не мелочь.** У них счётчик растёт сам
    от каждого повтора: «Оплатить интернет каждое 24-е» показывает 9 переносов,
    не будучи перенесённой ни разу. Без этой оговорки прибор объявил бы
    завалом всю рутину человека — и разговор о переносах умер бы в первый день.

    **Задачи со свежей записью рабочей сессии исключаем тоже.** Их перенос —
    продолжение работы, а не уклонение. Куплено живым уроком 30.07–04.08:
    пять переносов подряд, коуч читал их как уклонение и давил, а работа шла
    каждый день. `сессии` — множество id задач, у которых есть запись за вчера
    или сегодня; собирает его `свежие_сессии`, потому что для этого нужны
    комментарии, а прибор считает по списку задач и в сеть не ходит.

    **`@жду` и `@отложено` не считаем вовсе** (заявка владельца #110
    от 11.08.2026). У них дата означает не «делать тогда», а «вернуться тогда»
    (`С_ВОЗВРАТОМ`), и её перенос — это не «опять не сделал», а работа с делом
    ровно так, как задумано: мяч у другого человека либо пауза взята осознанно.
    Слова владельца: считать только то, что реально стоит на нём самом.
    Исключение того же рода уже стоит в `без_размера` — там его купили 06.08.
    """
    сессии = сессии or set()
    хроники = sorted(
        ((з, з.get("postponed_count") or 0) for з in задачи
         if not повторяющаяся(з)
         and str(з.get("id")) not in сессии
         and _состояние(з) not in С_ВОЗВРАТОМ
         and (з.get("postponed_count") or 0) >= порог),
        key=lambda пара: -пара[1],
    )
    if not хроники:
        return []
    перечень = ", ".join(f"«{з.get('content', '')}» — {n} раз" for з, n in хроники[:3])
    return [Отклонение(
        "завал", "Хронические переносы",
        f"Переезжает не первый раз ({len(хроники)} шт.): {перечень}. "
        f"Обычно это значит «великовато» или «не своё».",
    )]


def _дети(задачи: list[dict]) -> dict[str, list[dict]]:
    """Кто чей родитель. Считаем только по живым: закрытая подзадача не держит.

    Одна функция на все приборы оси состояния: «большая задача» опознаётся
    ровно одним способом — по наличию живых подзадач, — и способ этот обязан
    быть один на весь файл, иначе приборы разойдутся между собой.
    """
    живые = {з["id"] for з in задачи}
    дети: dict[str, list[dict]] = {}
    for з in задачи:
        род = з.get("parent_id")
        if род and род in живые:
            дети.setdefault(род, []).append(з)
    return дети


def _состояние(задача: dict) -> str:
    """Метка состояния задачи, или пустая строка. Их по правилу не больше одной."""
    for м in задача.get("labels") or []:
        if м in СОСТОЯНИЯ:
            return м
    return ""


def без_размера(задачи: list[dict]) -> list[Отклонение]:
    """Задачи без метки размера — там, где размер на что-то влияет.

    Правило «оценивай время каждой задаче» действует с 20.07 и держится плохо:
    на 01.08 живо на 42 % (59 из 140). Правило без прибора не выполняется,
    сколько бы раз его ни записали, — поэтому у него есть прибор.

    **Кого прибор НЕ считает и почему.** Раньше он смотрел на метку `актив`,
    и с уходом этой метки разрез пришлось выбирать заново. Замер 06.08.2026:

    | Разрез | Без размера |
    |---|---|
    | все бессрочные, не большие | 51 из 68 (75 %) |
    | со сроком плюс те, что вот-вот берут | 21 из 56 (38 %) |

    Первый разрез — лампочка, которая горит всегда, а такую человек перестаёт
    видеть на второй неделе. Берём второй: размер нужен там, где он работает.
    День считается **весом задач со сроком** — значит у них размер обязателен;
    `вработе` и `очередь` берут со дня на день — значит тоже. `жду` не считаем:
    там работа вообще не у нас. Кладовку не считаем тоже — складскому делу
    цена неизвестна и не нужна, и её отсеивает `видимые()`. Большие задачи не считаем: их размер живёт в подзадачах,
    и требовать его дважды — это заставлять человека врать.

    **Про `жду` тут было написано с 06.08.2026, а в коде этого не было.**
    Отбор шёл по «есть срок ИЛИ вработе/очередь», и задача `@жду` со сроком
    в него попадала — хотя дата у `@жду` значит не «делать тогда», а «мяч
    вернётся тогда» (`methodology/работа-в-todoist.md`, «Дата у `@жду`
    и `@отложено` значит другое»). Поймано разбором 09.08.2026 на живом
    аккаунте: «Списаться с Сашей» числилась долгом по размеру, будучи чужим
    ходом. Тот же класс, что два других промаха того же дня: **текст обещает
    одно, код делает другое** — и врёт при этом текст молча, потому что его
    никто не сверяет.
    """
    дети = _дети(задачи)
    важные = [
        з for з in задачи
        if з["id"] not in дети
        and _состояние(з) != "жду"
        and (_срок(з) is not None or _состояние(з) in ("вработе", "очередь"))
    ]
    без = [з for з in важные if not any(м in МИНУТЫ for м in з.get("labels") or [])]
    if not без or not важные:
        return []
    доля = round(100 * len(без) / len(важные))
    return [Отклонение(
        "прибор", "Без размера",
        f"Без метки размера {len(без)} задач из {len(важные)} ({доля} %) — среди тех, "
        f"где размер работает: со сроком и те, что вот-вот берут. "
        f"Без размера не посчитать, влезет ли день.",
        природа=ОФОРМЛЕНИЕ,
    )]


def потеряшки_список(задачи: list[dict]) -> list[dict]:
    """Кого прибор «Потеряшки» считает. Отдельно от текста отклонения затем,
    что тот же отбор нужен дашборду, а два отбора одного прибора разойдутся.

    **Большие задачи считаются наравне с одиночками.** Первая редакция их
    исключала — «у большой задачи состояние своё, его меряет „В игре“», — и это
    была дыра: «В игре» считает только тех, у кого метка `вработе` СТОИТ,
    а большая задача вообще без состояния не попадала никуда и была невидима
    обоим приборам. Замер 06.08.2026: таких на живом аккаунте три.

    Исключаем только подзадачи: у них контекст держит родитель.
    """
    return [
        з for з in задачи
        if not з.get("parent_id")
        and _срок(з) is None
        and not _состояние(з)
    ]


def в_игре_список(задачи: list[dict]) -> list[dict]:
    """Большие задачи в работе. Тот же отбор нужен дашборду — см. выше."""
    дети = _дети(задачи)
    return [з for з in задачи if з["id"] in дети and _состояние(з) == "вработе"]


def потеряшки(задачи: list[dict], сколько: int = 5) -> list[Отклонение]:
    """Бессрочная одиночка без метки состояния — дело, которое никто не видит.

    Раньше «Потеряшки» снимались фильтром `@актив & no date` и мерили пустоту:
    метку `актив` носили 8 задач на весь аккаунт (замер 05.08.2026), и прибор
    показывал ноль при 87 бессрочных делах. Ноль означал «всё в порядке» —
    ровно та болезнь, которую проект ловит с 01.08: **сторож, который видит
    не всё, показывает не тревогу, а спокойствие.**

    Теперь наоборот: потеряшка — это бессрочное дело, у которого НЕТ состояния.
    Его не видит ни «Сегодня», ни «Предстоящее», и человек не сказал про него
    ничего — ни «беру», ни «жду», ни «на склад». Оно просто лежит.

    Подзадачи исключены: у них контекст держит родитель. Большие задачи
    считаются наравне с одиночками — довод в `потеряшки_список`.
    """
    найдены = потеряшки_список(задачи)
    if not найдены:
        return []
    перечень = ", ".join(f"«{з.get('content', '')[:40]}»" for з in найдены[:сколько])
    хвост = f" и ещё {len(найдены) - сколько}" if len(найдены) > сколько else ""
    return [Отклонение(
        "завал", "Потеряшки",
        f"Бессрочных дел без состояния — {len(найдены)}: {перечень}{хвост}. "
        f"Их не видно ни в «Сегодня», ни в «Предстоящем». Каждому нужно "
        f"состояние: @очередь (возьму на днях), @жду, @отложено с датой "
        f"возврата — либо место в «Кладовке», если это не работа, а замысел.",
    )]


def в_игре(задачи: list[dict], норма: int = В_ИГРЕ_НОРМА) -> list[Отклонение]:
    """Сколько больших задач ведём одновременно. Норма — не больше пяти.

    Ради этого прибор и переделан. Старый считал `@актив & !no date` — задачи,
    и «сорок задач в игре» человеку не говорит ничего. Больших задач у него
    в голове помещается счётное число, и про пять против восьми он может судить
    сам, без всяких данных за год.

    **Норма названа числом, а не отложена.** Раньше здесь стояло «порог считается
    сам, когда накопится год данных», то есть прибора не было вовсе — был список.
    Пять: замер 06.08.2026 показал восемь шевелящихся больших задач, и владелец
    назначил пять, зная, что лампочка загорится в первый же вечер.
    """
    ведём = в_игре_список(задачи)
    if len(ведём) <= норма:
        return []
    перечень = ", ".join(f"«{з.get('content', '')[:40]}»" for з in ведём)
    return [Отклонение(
        "завал", "В игре",
        f"Больших задач в работе {len(ведём)} при норме {норма}: {перечень}. "
        f"Что-то из этого честнее отложить с датой возврата, чем делать вид, "
        f"что оно движется.",
    )]


# Сколько живых задач нужно метке, чтобы она была нужна. Порог из методологии,
# действует на все оси. Метка на одной задаче ничего не собирает: она просто
# вторая копия её имени.
#
# **Прибора на это НЕТ, и это решение, а не недоделка.** Прибор был написан
# и снят в тот же час 06.08.2026 по слову владельца: «я вообще не понимаю,
# с чего вдруг наклейка должна о чём-то сигнализировать». Довод верный
# и он про устройство: ночной обход отвечает на вопрос «что с моими ДЕЛАМИ»,
# а метки — это инструмент, которым дела размечены. Лампочка про аккуратность
# инструмента — шум в приборной панели про работу.
#
# Правило живёт там, где от него есть толк: у коуча в момент ЗАВЕДЕНИЯ метки
# (конституция, ядро) и в методологии. Число здесь затем, что на него ссылаются
# оба текста, и второй его копии заводить незачем.
МЕТКЕ_ЗАДАЧ = 3


def срок_и_метка(задачи: list[dict], сколько: int = 5) -> list[Отклонение]:
    """Срок сильнее метки: у задачи со сроком метки состояния быть не должно.

    Ловит `вработе` и `очередь` на задаче с датой. `жду` и `отложено`
    не ловит намеренно: у них дата — это день возврата к вопросу, а не срок,
    и стоять она там обязана.

    **Мягко, а не ругательно** — как и прибор на дату у большой задачи. Лечится
    одним движением, и каким именно, зависит от того, что человек имел в виду:
    либо снять метку (дело правда делается в этот день), либо снять дату (день
    назначен от неловкости, а не по делу).
    """
    найдены = [
        з for з in задачи
        if _срок(з) is not None and _состояние(з) in БЕЗ_ДАТЫ
    ]
    if not найдены:
        return []
    перечень = ", ".join(
        f"«{з.get('content', '')[:36]}» (@{_состояние(з)})" for з in найдены[:сколько]
    )
    хвост = f" и ещё {len(найдены) - сколько}" if len(найдены) > сколько else ""
    return [Отклонение(
        "прибор", "Срок и метка",
        f"У задачи со сроком стоит метка состояния ({len(найдены)} шт.): "
        f"{перечень}{хвост}. Срок сильнее метки: либо снимай метку, либо снимай "
        f"дату — вместе они спорят друг с другом.",
        природа=ОФОРМЛЕНИЕ,
    )]


def вернувшиеся(задачи: list[dict], с_полки: list[dict] | None = None,
                день: date | None = None) -> list[Отклонение]:
    """Всё, чей день возврата наступил: паузы в Todoist и отложенные записи полки.

    **Один прибор на два дома, и это осознанно.** Механизм у них буквально
    один: «отложить без числа — значит похоронить, поэтому у всякого „не сейчас“
    есть день, когда оно само постучится». В Todoist это метка `отложено`
    с датой, на полке коуча — статус «отложена» с полем `вернуться`
    (заявка №60 от 05.08.2026: `Inbox.вернувшиеся()` был написан и покрыт
    тестом, но его никто не звал, и первый отложенный факт всплыл бы в никуда).

    Двумя приборами это было бы двумя разными формулировками одной мысли,
    которые через месяц разойдутся.
    """
    сегодня = день or _сегодня()
    паузы = [
        з for з in задачи
        if _состояние(з) == "отложено" and (д := _срок(з)) is not None and д <= сегодня
    ]
    записи = с_полки or []
    if not паузы and not записи:
        return []
    куски = []
    if паузы:
        имена = ", ".join(f"«{з.get('content', '')[:36]}»" for з in паузы[:3])
        хвост = f" и ещё {len(паузы) - 3}" if len(паузы) > 3 else ""
        куски.append(f"в Todoist {len(паузы)}: {имена}{хвост}")
    if записи:
        имена = ", ".join(f"«{з.get('текст', '')[:36]}»" for з in записи[:3])
        хвост = f" и ещё {len(записи) - 3}" if len(записи) > 3 else ""
        куски.append(f"на полке {len(записи)}: {имена}{хвост}")
    return [Отклонение(
        "завал", "Вернувшаяся пауза",
        f"День возврата наступил — {'; '.join(куски)}. "
        f"Решай заново: берусь и ставлю срок, откладываю ещё раз — @отложено "
        f"с новой датой, — или убираю в «Кладовку».",
    )]


def большая_с_датой(задачи: list[dict], сколько: int = 3) -> list[Отклонение]:
    """Большие задачи (те, у кого есть живые подзадачи), у которых стоит своя дата.

    Правило «у большой задачи даты нет, сроки живут у подзадач» записано
    в методологии с самого начала и полтора месяца не выполнялось: на 05.08
    так стоял «Финальный модуль курса» — карточка на десяток шагов с датой,
    которая не наступает. Ровно тот случай, который проект ловит с 31.07:
    **правило без прибора не выполняется, сколько бы раз его ни записали.**

    Почему это вредно, а не некрасиво: дата означает «в этот день дело должно
    быть сделано», у большой задачи такого дня нет, и карточка каждый день висит
    в «сегодня» рядом с настоящими делами. Одна карточка-долгожитель обесценивает
    весь экран на сегодня.

    **Мягко, а не ругательно.** Жёсткий внешний дедлайн у большой задачи законен —
    вылет, эфир, срок подачи, — а отличить его от небрежности код не может:
    это суждение. Поэтому прибор показывает находку и оставляет вопрос человеку,
    ровно по правилу «обязательное делает код, суждение — модель».

    Повторяющиеся исключаем по той же причине, что и в переносах: у «оплатить
    интернет каждое 24-е» дата законна по природе.
    """
    родители = {род: len(список) for род, список in _дети(задачи).items()}
    if not родители:
        return []
    с_датой = [
        (з, родители[з["id"]]) for з in задачи
        if з["id"] in родители and _срок(з) is not None and not повторяющаяся(з)
    ]
    if not с_датой:
        return []
    с_датой.sort(key=lambda пара: -пара[1])
    перечень = ", ".join(
        f"«{з.get('content', '')}» ({n} подзадач)" for з, n in с_датой[:сколько]
    )
    return [Отклонение(
        "прибор", "Большая с датой",
        f"У большой задачи стоит своя дата ({len(с_датой)} шт.): {перечень}. "
        f"Такая дата не наступает и висит в «сегодня» каждый день — сроки "
        f"положено держать у подзадач. Если это жёсткий внешний дедлайн — так "
        f"и оставь, но скажи об этом вслух.",
        природа=ОФОРМЛЕНИЕ,
    )]


def без_сферы_список(задачи: list[dict]) -> list[dict]:
    """Кто именно без сферы. Отдельной функцией, чтобы дашборд считал тем же
    кодом, что и обход, — иначе панель и ночной свод разойдутся в показаниях."""
    return [
        з for з in задачи
        if not з.get("parent_id") and not (set(з.get("labels") or []) & set(СФЕРЫ))
    ]


def без_сферы(задачи: list[dict], сколько: int = 5) -> list[Отклонение]:
    """Задача без метки сферы. Норма — ноль, и она достижима.

    **Почему у сферы прибор есть, а у цели его не было.** У цели пропуск метки
    неотличим от нормы: у большинства задач цели нет, и это правильно, — значит
    забывчивость невидима и связка тихо гниёт. Ровно это и убило `@цель-*`.
    У сферы пропуск — всегда дырка, потому что сфера есть у каждой задачи без
    исключений. Лампочка не может гореть вечно: увидел, поставил, погасла.

    Подзадачи не считаем: по правилу от 06.08.2026 они идут за родителя, метка
    на карточке собирает работу по всему дереву. Кладовка сюда не попадает —
    её отсеивает `видимые()` до вызова.
    """
    найдены = без_сферы_список(задачи)
    if not найдены:
        return []
    перечень = ", ".join(f"«{з.get('content', '')[:36]}»" for з in найдены[:сколько])
    хвост = f" и ещё {len(найдены) - сколько}" if len(найдены) > сколько else ""
    return [Отклонение(
        "прибор", "Задача без сферы",
        f"Без метки сферы {len(найдены)} шт.: {перечень}{хвост}. "
        f"Сфера есть у каждого дела: {', '.join('@' + с for с in СФЕРЫ)}.",
        природа=ОФОРМЛЕНИЕ,
    )]


# Невидимые символы, которые ломают сравнение имён, а глазами не видны:
# нулевой пробел, неразрывный пробел, мягкий перенос. Имя цели человек
# переносит РУКАМИ между Todoist и памятью, а копирование через браузер или
# телефон приносит их регулярно. Без нормализации прибор «Имя цели не найдено»
# горел бы вечно, и погасить его было бы нечем: строки на вид одинаковые.
НЕВИДИМЫЕ = str.maketrans({"\u200b": "", "\u00ad": "", "\ufeff": "", "\u00a0": " "})


def _ровно(имя: str | None) -> str:
    """Имя, приведённое к виду, в котором его можно честно сравнивать."""
    return " ".join((имя or "").translate(НЕВИДИМЫЕ).split())


def цель_без_карточки(имена: list[str], задачи: list[dict]) -> list[Отклонение]:
    """Имя цели из горизонтов, которого нет в Todoist ни на одной задаче.

    **Связка по имени, а не по адресу.** Адрес ломается молча: 07.08.2026
    в горизонтах стояло «→ секция 💰 Автопродукт (осень)» и «→ секция Сделать
    перед переездом», а обеих секций в Todoist уже не было — и никто этого не знал.
    Имя ломается видимо, и расхождение ловит код.

    Смотрим по ВСЕМ задачам, включая спрятанные проекты: цель, уехавшая
    в Кладовку, — это разговор на стратсессии, а не пропажа. Прибор отвечает
    ровно на один вопрос: «эта карточка вообще существует?».
    """
    живые = {_ровно(з.get("content")) for з in задачи}
    пропали = [и for и in имена if _ровно(и) not in живые]
    if not пропали:
        return []
    перечень = ", ".join(f"«{и[:36]}»" for и in пропали)
    return [Отклонение(
        "прибор", "Имя цели не найдено",
        f"В горизонтах названы карточки, которых в Todoist нет ({len(пропали)}): "
        f"{перечень}. Либо карточку переименовали — поправь горизонты, либо "
        f"работа под целью не заведена вовсе.",
    )]


# ── память сторожа: что держится дольше нормы ────────────────────────────────

# Сколько суток подряд прибор должен быть не в норме, чтобы это перестало быть
# жизнью и стало долгом. Три: один день — обычное дело, два — совпадение,
# три — уже свойство. Число здесь, а не в промпте: его меняют по прожитому.
ДЕРЖИТСЯ_ДНЕЙ = 3

# Через сколько дней напомнить, если отклонение живо, а задачу уже закрыли.
#
# Куплено разбором 05.08.2026. Отметка «поднято» снималась ТОЛЬКО при
# восстановлении нормы — значит человек, закрывший задачу руками, ничего
# не починив, больше про это отклонение не слышал никогда. Дымовая сигнализация
# с кнопкой «выключить писк»: писк выключен, дым остался.
#
# Неделя, а не сутки: сутки вернули бы ровно тот шум, от которого защищались
# порогом в три дня. Неделя — такт, в котором проект и так живёт.
НАПОМНИТЬ_ЧЕРЕЗ = 7

ПАМЯТЬ = """
CREATE TABLE IF NOT EXISTS detector_streak (
    имя       TEXT PRIMARY KEY,
    впервые   TEXT NOT NULL,
    последний TEXT NOT NULL,
    поднято   TEXT NOT NULL DEFAULT ''
);
"""


def давность(db_path: Path, свод: Свод, день: date | None = None) -> dict[str, int]:
    """Сколько суток подряд горит каждая лампочка свода. Только чтение.

    Отдельная функция, а не довесок к `запомнить`, и это главное её свойство:
    `запомнить` ПИШЕТ — двигает счётчики и отмечает поднятое, — и звать её
    утром ради справки значило бы каждым чек-ином подтверждать «поднято»,
    то есть глушить ночную задачу. Утреннему коучу нужно только посмотреть.

    Заведена по заявке владельца #111 (11.08.2026): чтобы коуч мог не
    докладывать о зависшем, а предложить разгрести. База не отвечает —
    пустой словарь: свод обязан доехать до чек-ина даже без этой приправы.
    """
    день = день or _сегодня()
    имена = {о.имя for о in свод.отклонения if о.класс != "мелочь"}
    if not имена:
        return {}
    try:
        with sqlite3.connect(db_path, timeout=30) as db:
            db.executescript(ПАМЯТЬ)
            строки = db.execute("SELECT имя, впервые FROM detector_streak").fetchall()
    except sqlite3.Error:
        log.warning("давность отклонений не снялась — свод поедет без пометок")
        return {}
    сколько = {}
    for имя, впервые in строки:
        if имя not in имена:
            continue
        try:
            сколько[имя] = (день - date.fromisoformat(впервые)).days + 1
        except ValueError:
            continue
    return сколько


def запомнить(db_path: Path, свод: Свод, день: date | None = None,
              порог: int = ДЕРЖИТСЯ_ДНЕЙ, поднимать: bool = True) -> list[Отклонение]:
    """Отметить сегодняшние отклонения и вернуть те, что держатся дольше нормы.

    Зачем помнить. Прибор без реакции — декорация (решение 31.07). Но дёргать
    задачей на каждое отклонение значит засорить Todoist собственным шумом:
    просроченная задача в четверг — обычная жизнь. Дёргаем, когда лампочка
    горит третьи сутки подряд, и ровно один раз за приступ: восстановилась
    норма — счёт обнуляется, загорелась снова — начинается заново.

    «Мелочь дня» сюда не попадает никогда: это предложение лёгкого, а не долг.

    Поднимается только природа ДВИЖЕНИЕ (заявка владельца #173, 22.08.2026):
    оформление коуч правит сам и молча, карточкой за него не дёргают. Счётчик
    суток при этом идёт всем — он нужен ещё и утреннему чек-ину.

    `поднимать=False` — ночь не в день ревизии: счётчики двигаются, отметка
    «поднято» не ставится, наверх не уходит ничего. Иначе созревшее в понедельник
    отметилось бы поднятым в понедельник и до среды не дожило.
    """
    день = день or _сегодня()
    сегодня = день.isoformat()
    живые = {о.имя: о for о in свод.отклонения if о.класс != "мелочь"}

    db_path.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(db_path, timeout=30) as db:
        db.executescript(ПАМЯТЬ)
        было = {
            имя: (впервые, поднято)
            for имя, впервые, поднято in db.execute(
                "SELECT имя, впервые, поднято FROM detector_streak"
            )
        }
        # Норма восстановилась — забываем приступ целиком, вместе с отметкой.
        for имя in set(было) - set(живые):
            db.execute("DELETE FROM detector_streak WHERE имя = ?", (имя,))

        созревшие: list[Отклонение] = []
        for имя, отклонение in живые.items():
            впервые, поднято = было.get(имя, (сегодня, ""))
            db.execute(
                "INSERT INTO detector_streak(имя, впервые, последний, поднято)"
                " VALUES(?,?,?,?) ON CONFLICT(имя) DO UPDATE SET последний = excluded.последний",
                (имя, впервые, сегодня, поднято),
            )
            держится = (день - date.fromisoformat(впервые)).days + 1
            if держится < порог or not поднимать or отклонение.природа != ДВИЖЕНИЕ:
                continue
            # Не поднимали вовсе — поднимаем. Поднимали, но с тех пор прошла
            # неделя, а лампочка всё горит — значит задачу закрыли, ничего
            # не починив, и напомнить обязаны мы: сама она не вернётся.
            остыло = поднято and (день - date.fromisoformat(поднято)).days >= НАПОМНИТЬ_ЧЕРЕЗ
            if поднято and not остыло:
                continue
            db.execute("UPDATE detector_streak SET поднято = ? WHERE имя = ?",
                       (сегодня, имя))
            созревшие.append(отклонение)
    return созревшие


# ── обход целиком ────────────────────────────────────────────────────────────

async def свободные_часы(calendar: dict | None, дней: int = 7) -> tuple[dict[str, float], str]:
    """Сколько часов реально свободно в ближайшие дни. Возвращает (часы, жалоба)."""
    if not calendar:
        return {}, "календарь не подключён — перегруз считаю от рабочего дня"
    try:
        from gcal_mcp.client import CalendarClient, CalendarError
        from gcal_mcp.core import free_windows
    except ImportError as err:  # пакета нет — не повод ронять обход
        return {}, f"календарь недоступен ({err})"

    try:
        async with CalendarClient(**calendar) as client:
            _, окна = await free_windows(
                client, date_from=_сегодня().isoformat(),
                date_to=(_сегодня() + timedelta(days=дней)).isoformat(), min_minutes=30,
            )
    except (CalendarError, OSError) as err:
        log.warning("свободные окна не забрались: %s", err)
        return {}, "календарь не ответил — перегруз считаю от рабочего дня"

    часы = {
        день: round(sum((к - н).total_seconds() for н, к in окна) / 3600, 1)
        for день, окна in окна.items()
    }
    return часы, ""


async def обойти(token: str, db_path: Path, calendar: dict | None = None,
                 полка: Any | None = None, горизонты: Path | None = None) -> Свод:
    """Один обход: живой Todoist + снимки + календарь + полка. Ноль токенов.

    Todoist не ответил — возвращаем то, что успели, и говорим об этом.
    Молча отдавать пустой свод нельзя: пустой свод означает «всё в порядке».

    `полка` — необязательна: без неё прибор «Вернувшаяся пауза» смотрит только
    в Todoist. Необязательна потому, что обход старше полки и обязан работать
    там, где полки нет; молчать про Todoist из-за отсутствия полки было бы
    той же болезнью «сторож видит не всё».

    `горизонты` — путь к `состояние/горизонты.md`; без него молчит прибор
    «Имя цели не найдено». По той же причине необязателен: у ученика на первом
    запуске целей нет вовсе.
    """
    свод = Свод()
    свободно, жалоба = await свободные_часы(calendar)
    if жалоба:
        свод.жалобы.append(жалоба)

    try:
        async with TodoistClient(token) as client:
            всё_подряд = await client.get_paginated("/tasks", params={"limit": 200}, cap=1000)
            все = видимые(await мои(client, всё_подряд), await _спрятанные_проекты(client))
            сессии = await свежие_сессии(client, все)
            показания = [
                (имя, len(await по_фильтру(client, запрос)), норма)
                for имя, запрос, норма in GAUGES
            ]
    except (TodoistError, OSError) as err:
        log.error("обход завалов не состоялся: %s", err)
        свод.жалобы.append(f"Todoist не ответил ({err})")
        return свод

    с_полки: list[dict] = []
    if полка is not None:
        try:
            с_полки = полка.вернувшиеся()
        except Exception:  # полка не ответила — Todoist всё равно обязан прозвучать
            log.exception("полка не отдала вернувшиеся записи")
            свод.жалобы.append("полка не ответила про отложенные записи")

    свод.отклонения += перегруз(все, свободно)
    свод.отклонения += баланс_недели(все)
    свод.отклонения += хронические_переносы(все, сессии=сессии)
    свод.отклонения += без_размера(все)
    свод.отклонения += большая_с_датой(все)
    свод.отклонения += потеряшки(все)
    свод.отклонения += в_игре(все)
    свод.отклонения += срок_и_метка(все)
    свод.отклонения += вернувшиеся(все, с_полки)
    свод.отклонения += без_сферы(все)
    if горизонты is not None:
        # По всем задачам, а не только по видимым: цель, уехавшая в Кладовку,
        # существует — это повод для разговора на стратсессии, а не пропажа.
        свод.отклонения += цель_без_карточки(
            horizons.имена_карточек(горизонты), всё_подряд,
        )
    свод.отклонения += мелочь(все)

    for имя, факт, норма in показания:
        исправен = норма == "—" or (норма in ("пусто", "0") and факт == 0)
        if исправен:
            свод.в_норме.append(f"{имя.lower()} {факт}" if норма == "—" else имя.lower())
        else:
            свод.отклонения.append(Отклонение(
                "прибор", имя, f"{имя}: {факт} при норме «{норма}».",
            ))
    return свод
