# Две природы отклонений, и это разные разговоры (заявка владельца #173,
# 22.08.2026). ДВИЖЕНИЕ — про жизнь: дело переезжает шестой раз, потерялось,
# стоит месяцем. ОФОРМЛЕНИЕ — про то, как заполнена строчка: нет метки размера,
# нет сферы, у мастер-карточки своя дата, срок спорит с меткой.
#
# Куплено тем, что обе природы валились в одну карточку «Разгрести»: человек
# открывал её ради застрявших дел, а находил претензии к меткам — «ни разу
# ничего полезного я в ней не нашёл». Оформление коуч правит сам и молча,
# инструменты у него для этого есть; в ревизию идёт только движение.
ДВИЖЕНИЕ, ОФОРМЛЕНИЕ = "движение", "оформление"


@dataclass(frozen=True)
class Отклонение:
    """Прибор вне нормы. `строка` — то, что увидит коуч; остальное для порядка."""

    класс: str      # чем это лечится: «завал», «прибор», «мелочь»
    имя: str
    строка: str
    # Умолчание — ДВИЖЕНИЕ: прибор, про природу которого забыли подумать,
    # скорее про жизнь, и промолчать про застрявшее дело дороже, чем лишний
    # раз показать человеку метку.
    природа: str = ДВИЖЕНИЕ


@dataclass
class Свод:
    """Что сторож увидел за один обход."""

    отклонения: list[Отклонение] = field(default_factory=list)
    в_норме: list[str] = field(default_factory=list)
    жалобы: list[str] = field(default_factory=list)  # чего не удалось посмотреть

    def пусто(self) -> bool:
        return not self.отклонения

    def текст(self, давности: dict[str, int] | None = None) -> str:
        """Свод для подстановки в чек-ин. Пусто — пустая строка, и это ответ.

        `давности` — сколько суток подряд горит каждая лампочка (имя → суток).
        Те, что горят третьи сутки и дольше, помечаются прямо в строке: заявка
        владельца #111 от 11.08.2026. До этого «висит третьи сутки» знала только
        ночь — она заводила про это задачу в Todoist, — а утренний коуч видел
        ровно тот же список, что и в первый день, и говорил о нём тем же тоном.
        Разница между «сегодня перегруз» и «перегруз третьи сутки» — это разница
        между замечанием и долгом, и она обязана быть видна тому, кто говорит.
        """
        if self.пусто() and not self.жалобы:
            return ""
        давности = давности or {}
        куски = []
        for о in self.отклонения:
            if о.природа == ОФОРМЛЕНИЕ:
                continue
            суток = давности.get(о.имя, 0)
            хвост = f" [висит {суток}-е сутки]" if суток >= ДЕРЖИТСЯ_ДНЕЙ else ""
            куски.append(f"- {о.строка}{хвост}")
        # Оформление — отдельным блоком и с другим поручением. Свалить его
        # в общий список значит вернуть ровно то, из-за чего разгребание
        # перестали читать: претензии к меткам вперемешку с застрявшими делами.
        оформление = [о for о in self.отклонения if о.природа == ОФОРМЛЕНИЕ]
        if оформление:
            куски.append(ОФОРМЛЕНИЕ_ЗАГОЛОВОК)
            куски += [f"  - {о.строка}" for о in оформление]
        if self.в_норме:
            куски.append(f"- В норме: {', '.join(self.в_норме)}.")
        куски += [f"- Не посмотрел: {ж}" for ж in self.жалобы]
        return ЗАГОЛОВОК + "\n" + "\n".join(куски)


# ── время ────────────────────────────────────────────────────────────────────

def _зона() -> ZoneInfo:
    return ZoneInfo(os.environ.get("COACH_TZ") or "Europe/Moscow")


def _сегодня() -> date:
    return datetime.now(_зона()).date()


def _срок(задача: dict) -> date | None:
    сырое = (задача.get("due") or {}).get("date") or ""
    try:
        return date.fromisoformat(сырое[:10])
    except ValueError:
        return None


def _часы(задачи: list[dict]) -> float:
    минут = sum(МИНУТЫ.get(м, 0) for з in задачи for м in з.get("labels") or [])
    return round(минут / 60, 1)


# ── чтение Todoist ───────────────────────────────────────────────────────────

async def _спрятанные_проекты(client: TodoistClient) -> set[str]:
    """id проектов, которых приборы не касаются. Не ответил — пустое множество:
    показать лишнее честнее, чем молча промолчать про настоящий завал."""
    try:
        проекты = await client.get_paginated("/projects", params={"limit": 200}, cap=200)
    except TodoistError as err:
        log.warning("список проектов не снялся, «Архив» не спрятан: %s", err)
        return set()
    return {
        str(п["id"]) for п in проекты
        if (п.get("name") or "").strip().lower() in НЕ_СМОТРИМ
    }


def видимые(задачи: list[dict], спрятанные: set[str]) -> list[dict]:
    """Задачи вне спрятанных проектов. Один отбор на все приборы разом —
    иначе половина смотрела бы в «Архив», а половина нет."""
    if not спрятанные:
        return задачи
    return [з for з in задачи if str(з.get("project_id") or "") not in спрятанные]


async def мои(client: TodoistClient, задачи: list[dict]) -> list[dict]:
    """Без чужих задач общего проекта — один отбор на всех читателей бота.

    В общем проекте работают двое, у каждого свой коуч, и оба читают все
    задачи подряд. Без этого отбора коуч дожимал бы человека чужими делами,
    а приборы считали бы чужие просрочки своими. Чья задача — решает
    `todoist_mcp.people` (исполнитель, а без него — кто завёл): правило одно
    на инструмент и на бота. Todoist не ответил про людей — всё считается
    своим, то есть как до общих проектов.
    """
    люди = await people.загрузить(client)
    return [з for з in задачи if not люди.чужая(з)]


async def по_фильтру(client: TodoistClient, запрос: str, limit: int = 100) -> list[dict]:
    """Мои задачи по запросу Todoist. Не ответил — пусто и жалоба в лог."""
    try:
        data = await client.get("/tasks/filter", params={"query": запрос, "limit": limit})
    except TodoistError as err:
        log.warning("прибор «%s» не снялся: %s", запрос, err)
        return []
    return await мои(client, data.get("results", []) if isinstance(data, dict) else (data or []))



