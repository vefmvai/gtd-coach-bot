"""Входящие коуча: одна полка на четыре вида находок.

До 05.08.2026 копилки жили тремя markdown-файлами в мозге, а «разобрано»
означало зачёркивание строки — `- ~~строка~~`. Отметка в форматировании
держится на памяти человека и не держится: на живом мозге 18 заявок и **ноль**
вычеркнутых, при том что заявка про словарь Whisper закрыта 03.08 и итог
записан в другом месте. Статус в базе забыть нельзя: либо закрыл, либо нет.

**Одна таблица, а не четыре по видам.** Разбираются они одинаково — посмотрел,
решил, закрыл с итогом; четыре таблицы были бы одним кодом в четырёх местах.
Та же болезнь, которую этап 14 лечил у списка инструментов.

**Ярлыка «человек / машина» нет:** вид его уже несёт. `заявка` бывает только
человеческой, остальные три — только машинными. Второй ярлык повторял бы
первый и требовал бы за собой следить. Правило записано, чтобы его не сломали:
если однажды понадобится «автоматическая заявка» — сначала проверить, не поломка
ли это на самом деле.

**У поломки один счётчик, а не запись на каждую ночь.** Ночь находит одно и то
же по многу раз подряд; заводить строку на каждую находку значило бы завалить
полку копиями. Поэтому у открытой записи растёт `случаев`.

**Чисел два, и они отвечают на разные вопросы.** Путать их дорого.

| Число | Откуда | Вопрос | Что делать |
|---|---|---|---|
| `случаев` | открытая запись | долго ли не доходят руки | просто почини |
| `чинили()` | закрытые записи | возвращается ли поломка | ищи причину |

`случаев` растёт, пока запись ОТКРЫТА, то есть меряет ночи, в которые поломку
нашли и не починили. До 09.08.2026 текст задачи выдавал это число за повторы
(«случилось N-й раз, повтор — признак: чинить надо причину»), и человек шёл
искать системную причину там, где просто двое суток не доходили руки.

Второе число завелось в тот же день и закрыло дыру побольше: настоящего
повтора копилка не видела ВООБЩЕ. Починил, закрыл, сломалось снова — счёт
с единицы, третий приступ выглядит первым. То есть глухота бота 03.08, ради
которой копилку и заводили, этим механизмом бы не опозналась.
"""

from __future__ import annotations

import logging
import sqlite3
from datetime import date, datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

log = logging.getLogger(__name__)

MOSCOW = ZoneInfo("Europe/Moscow")

# Четыре вида. Кириллицей: это значения в нашей базе, а не имена полей схемы
# MCP — там латиница обязательна (см. recall.py, зонд 02.08).
ЗАЯВКА = "заявка"
ПРЕДЛОЖЕНИЕ = "предложение"
ПРОМАХ = "промах"
ПОЛОМКА = "поломка"
ВИДЫ = (ЗАЯВКА, ПРЕДЛОЖЕНИЕ, ПРОМАХ, ПОЛОМКА)

# Пять статусов. Меньше — не хватает, больше — человек в них путается.
НОВАЯ = "новая"
В_РАБОТЕ = "в работе"
СДЕЛАНА = "сделана"
ОТКЛОНЕНА = "отклонена"
ОТЛОЖЕНА = "отложена"
СТАТУСЫ = (НОВАЯ, В_РАБОТЕ, СДЕЛАНА, ОТКЛОНЕНА, ОТЛОЖЕНА)

# Закрытые статусы: в застой не идут и в разборе не показываются.
ЗАКРЫТЫЕ = (СДЕЛАНА, ОТКЛОНЕНА)

# Норма копилки: невычеркнутых записей старше двух недель нет. Две недели —
# это два пропущенных недельных обзора подряд, а разбирать положено на каждом.
# Один пропуск — обычная жизнь, два — уже долг. Число переехало из memory_watch
# как есть: оно куплено решением 04.08 и с переездом не менялось.
ЗАСТОЙ_ДНЕЙ = 14

СХЕМА = """
CREATE TABLE IF NOT EXISTS inbox (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    вид        TEXT NOT NULL,             -- заявка | предложение | промах | поломка
    день       TEXT NOT NULL,             -- когда находка появилась, ГГГГ-ММ-ДД
    создано    TEXT NOT NULL,             -- отметка времени записи
    текст      TEXT NOT NULL,             -- что именно нашли
    зачем      TEXT NOT NULL DEFAULT '',  -- пояснение, если есть
    ключ       TEXT NOT NULL DEFAULT '',  -- у поломки — её вид; у остальных пусто
    случаев    INTEGER NOT NULL DEFAULT 1,-- ночей висит; растёт только у поломки
    последний  TEXT NOT NULL DEFAULT '',  -- день последнего повтора
    статус     TEXT NOT NULL DEFAULT 'новая',
    итог       TEXT NOT NULL DEFAULT '',  -- чем кончилось; у закрытой обязателен
    разобрано  TEXT NOT NULL DEFAULT '',  -- день разбора
    вернуться  TEXT NOT NULL DEFAULT '',  -- у отложенной обязателен: «потом» без числа — «никогда»
    карточка   TEXT NOT NULL DEFAULT ''   -- id карточки Todoist, пока она жива
);
CREATE INDEX IF NOT EXISTS inbox_вид ON inbox(вид, статус);
"""

# Колонки, дописанные к уже живой базе. Пересоздать таблицу нельзя: в ней лежат
# все входящие с 05.08.2026, и это единственный экземпляр.
ДОПИСАННЫЕ = (
    ("карточка", "TEXT NOT NULL DEFAULT ''"),
)


def _сегодня() -> date:
    return datetime.now(MOSCOW).date()


class Inbox:
    """Полка входящих в той же базе, где архив разговоров.

    База одна, потому что она уже попадает в штатный бэкап сервера; второй файл
    потребовал бы второго бэкапа. Модуль отдельный, потому что тема другая:
    `archive.py` про разговоры, схема живёт рядом с тем, кто её читает.
    """

    def __init__(self, path: Path) -> None:
        self.path = path
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self._connect() as db:
            db.executescript(СХЕМА)
            self._дописать_колонки(db)

    @staticmethod
    def _дописать_колонки(db: sqlite3.Connection) -> None:
        """Довести старую базу до нынешней схемы.

        `CREATE TABLE IF NOT EXISTS` молчит о таблице, которая уже есть, — новая
        колонка в тексте схемы до живой базы не доедет, и код упадёт на первом же
        запросе к ней. Проверяем по факту, а не по номеру версии: номер тоже надо
        где-то хранить, и он врёт ровно тогда, когда его забыли поднять.
        """
        есть = {строка[1] for строка in db.execute("PRAGMA table_info(inbox)")}
        for имя, тип in ДОПИСАННЫЕ:
            if имя not in есть:
                db.execute(f"ALTER TABLE inbox ADD COLUMN {имя} {тип}")
                log.info("полка: дописана колонка «%s»", имя)

    def _connect(self) -> sqlite3.Connection:
        db = sqlite3.connect(self.path, timeout=30)
        db.execute("PRAGMA journal_mode=WAL")
        return db

    # ── запись ───────────────────────────────────────────────────────────────

    def положить(self, вид: str, текст: str, *, зачем: str = "", день: date | None = None,
                 ключ: str = "") -> int:
        """Положить находку. Возвращает id записи.

        У поломки с уже открытой записью того же ключа новая строка НЕ заводится:
        растёт счётчик и обновляется день последней находки. Счётчик меряет
        НОЧИ, в которые поломку нашли и не починили, — не число поломок:
        закрытая запись в поиск не идёт, и следующая такая же начнёт с единицы.
        """
        if вид not in ВИДЫ:
            raise ValueError(f"неизвестный вид входящего: {вид}")
        текст = текст.strip()
        if not текст:
            raise ValueError("пустая находка — нечего класть")
        день = день or _сегодня()
        сейчас = datetime.now(MOSCOW).isoformat(timespec="seconds")

        with self._connect() as db:
            if вид == ПОЛОМКА and ключ:
                строка = db.execute(
                    "SELECT id, случаев FROM inbox WHERE вид=? AND ключ=? AND статус NOT IN (?,?)"
                    " ORDER BY id LIMIT 1",
                    (ПОЛОМКА, ключ, *ЗАКРЫТЫЕ),
                ).fetchone()
                if строка:
                    id_, случаев = строка
                    db.execute(
                        "UPDATE inbox SET случаев=?, последний=?, текст=? WHERE id=?",
                        (случаев + 1, день.isoformat(), текст, id_),
                    )
                    log.info("поломка «%s» висит %d-ю ночь", ключ, случаев + 1)
                    return int(id_)
            cur = db.execute(
                "INSERT INTO inbox(вид, день, создано, текст, зачем, ключ, случаев, последний, статус)"
                " VALUES(?,?,?,?,?,?,?,?,?)",
                (вид, день.isoformat(), сейчас, текст, зачем.strip(), ключ,
                 1, день.isoformat(), НОВАЯ),
            )
            return int(cur.lastrowid or 0)

    def поломка(self, ключ: str, текст: str, день: date | None = None) -> int:
        """Записать поломку и сказать, которую ночь подряд она висит.

        Отдельный вход, а не флаг у `положить`: счётчик зовут ровно оттуда,
        где потом печатают «висит N-ю ночь», и возвращать его всем остальным
        видам было бы обещанием, которого они не выполняют. Логика счёта при
        этом одна и живёт в `положить`.
        """
        id_ = self.положить(ПОЛОМКА, текст, день=день, ключ=ключ)
        запись = self.запись(id_)
        return int(запись["случаев"]) if запись else 1

    def запомнить_карточку(self, id_: int, карточка: str) -> bool:
        """Связать запись с карточкой Todoist, которую под неё завели.

        Без этой связи закрытие записи не гасит карточку, и та висит, пока
        кто-нибудь не вспомнит руками. 13.08.2026 не вспомнил никто: заявка #129
        была сделана и закрыта, а её карточка досталась владельцу — он и заметил.
        Пять предыдущих раз пронесло только потому, что закрывали в тот же час.
        """
        карточка = (карточка or "").strip()
        if not карточка:
            return False
        with self._connect() as db:
            cur = db.execute("UPDATE inbox SET карточка=? WHERE id=?", (карточка, id_))
            return cur.rowcount > 0

    def непогашенные(self, limit: int = 50) -> list[dict]:
        """Закрытые записи, чья карточка в Todoist ещё жива.

        Список для того, кто умеет ходить в сеть. Сама полка в Todoist не ходит
        намеренно: это слой базы, и синхронный SQL не место для сетевого запроса,
        который может висеть тридцать секунд.
        """
        поля = ("id", "вид", "карточка", "итог")
        with self._connect() as db:
            return [dict(zip(поля, строка)) for строка in db.execute(
                f"SELECT {', '.join(поля)} FROM inbox"
                " WHERE карточка != '' AND статус IN (?,?) ORDER BY id LIMIT ?",
                (*ЗАКРЫТЫЕ, limit),
            )]

    def карточка_погашена(self, id_: int) -> bool:
        """Забыть карточку: её больше нет, гасить нечего."""
        with self._connect() as db:
            cur = db.execute("UPDATE inbox SET карточка='' WHERE id=?", (id_,))
            return cur.rowcount > 0

    def запись(self, id_: int) -> dict | None:
        """Одна запись целиком, включая закрытые. Нет такой — None."""
        поля = ("id", "вид", "день", "текст", "зачем", "ключ", "случаев",
                "последний", "статус", "итог", "разобрано", "вернуться", "карточка")
        with self._connect() as db:
            строка = db.execute(
                f"SELECT {', '.join(поля)} FROM inbox WHERE id=?", (id_,)
            ).fetchone()
        return dict(zip(поля, строка)) if строка else None

    def закрыть(self, id_: int, статус: str, итог: str, *, вернуться: str = "",
                день: date | None = None) -> bool:
        """Закрыть запись с итогом. Возвращает False, если такой записи нет.

        **Пустой итог не принимается ни в одном статусе.** Отклонённое без причины
        через месяц предложат заново — это уже правило проекта про зачёркнутые
        решения. У отложенной обязательна дата возврата: «потом» без числа —
        это «никогда», и запись становится похороненной, а не отложенной.
        """
        if статус not in СТАТУСЫ:
            raise ValueError(f"неизвестный статус: {статус}")
        итог = итог.strip()
        if not итог:
            raise ValueError("итог обязателен: без него запись через месяц вернётся заново")
        if статус == ОТЛОЖЕНА and not вернуться.strip():
            raise ValueError("у отложенной записи обязательна дата возврата")

        день = день or _сегодня()
        with self._connect() as db:
            cur = db.execute(
                "UPDATE inbox SET статус=?, итог=?, разобрано=?, вернуться=? WHERE id=?",
                (статус, итог, день.isoformat(), вернуться.strip(), id_),
            )
            return cur.rowcount > 0

    # ── чтение ───────────────────────────────────────────────────────────────

    def чинили(self, ключ: str) -> int:
        """Сколько раз эту поломку уже закрывали починенной.

        Память о НАСТОЯЩИХ повторах — и второе из двух чисел, без которого
        копилка не делала того, ради чего заводилась. Счётчик `случаев` смотрит
        только на открытую запись и потому меряет «сколько ночей не доходят
        руки». Починил, закрыл, сломалось снова — счёт начинается с единицы,
        и третий приступ выглядит первым. Ровно так глухота бота 03.08.2026
        опозналась третьим случаем только потому, что предыдущие два человек
        записал в инциденты руками.

        Считаются только записи со статусом «сделана». «Отклонена» значит
        «разобрались и решили, что чинить нечего», — это не починка, и выдавать
        её за возврат поломки нельзя.

        Отдельной проверки на пустой ключ нет намеренно: запрос и так вернёт
        ноль, а строка, которую не может уронить ни одна мутация, — это строка,
        которую не держит ни один тест.
        """
        with self._connect() as db:
            строка = db.execute(
                "SELECT COUNT(*) FROM inbox WHERE вид=? AND ключ=? AND статус=?",
                (ПОЛОМКА, ключ, СДЕЛАНА),
            ).fetchone()
        return int(строка[0]) if строка else 0

    def открытые(self, вид: str = "", limit: int = 100) -> list[dict]:
        """Незакрытые записи, старые сверху: разбирают с самого залежавшегося."""
        запрос = ("SELECT id, вид, день, текст, зачем, статус, случаев, последний, вернуться"
                  " FROM inbox WHERE статус NOT IN (?,?)")
        параметры: list = list(ЗАКРЫТЫЕ)
        if вид:
            запрос += " AND вид=?"
            параметры.append(вид)
        запрос += " ORDER BY день, id LIMIT ?"
        параметры.append(limit)
        поля = ("id", "вид", "день", "текст", "зачем", "статус", "случаев", "последний", "вернуться")
        with self._connect() as db:
            return [dict(zip(поля, строка)) for строка in db.execute(запрос, параметры)]

    def отклонённые(self, вид: str = "", limit: int = 100) -> list[dict]:
        """Отклонённое с причиной, свежее сверху: чтобы не предлагать его снова."""
        запрос = "SELECT id, вид, день, текст, итог FROM inbox WHERE статус=?"
        параметры: list = [ОТКЛОНЕНА]
        if вид:
            запрос += " AND вид=?"
            параметры.append(вид)
        запрос += " ORDER BY день DESC, id DESC LIMIT ?"
        параметры.append(limit)
        поля = ("id", "вид", "день", "текст", "итог")
        with self._connect() as db:
            return [dict(zip(поля, строка)) for строка in db.execute(запрос, параметры)]

    def сколько(self) -> dict[str, int]:
        """Сколько открытого по каждому виду. Ноль не показываем — его и нет."""
        with self._connect() as db:
            return {
                вид: число
                for вид, число in db.execute(
                    "SELECT вид, COUNT(*) FROM inbox WHERE статус NOT IN (?,?) GROUP BY вид",
                    ЗАКРЫТЫЕ,
                )
            }

    def застой(self, сегодня: date | None = None, порог: int = ЗАСТОЙ_ДНЕЙ) -> tuple[int, str]:
        """Сколько записей висит дольше нормы и с какого дня.

        **Считаем все виды, а не одни предложения.** До переезда норма была
        только у предложений (`memory_watch.залежалось`, 04.08), и заявки копились
        без прибора вовсе — 18 строк, ноль вычеркнутых. Правило без прибора
        не выполняется, сколько бы раз его ни записали.

        **Отложенная в застой не идёт:** у неё своя дата возврата, и ругаться
        на то, что человек сознательно отложил, — значит завести сторожа, который
        врёт. Сторож, который врёт, приучает себя не читать.
        """
        сегодня = сегодня or _сегодня()
        рубеж = (сегодня - timedelta(days=порог)).isoformat()
        with self._connect() as db:
            строка = db.execute(
                "SELECT COUNT(*), MIN(день) FROM inbox"
                " WHERE статус NOT IN (?,?) AND статус!=? AND день<=?",
                (*ЗАКРЫТЫЕ, ОТЛОЖЕНА, рубеж),
            ).fetchone()
        висит = int(строка[0] or 0)
        старая = строка[1] or ""
        if висит:
            log.info("копилка входящих: %d записей висит дольше %d дней, самая старая от %s",
                     висит, порог, старая)
        return висит, старая

    def вернувшиеся(self, сегодня: date | None = None) -> list[dict]:
        """Отложенные, у которых наступил день возврата. Отложить — не похоронить."""
        сегодня = сегодня or _сегодня()
        поля = ("id", "вид", "день", "текст", "вернуться")
        with self._connect() as db:
            return [
                dict(zip(поля, строка))
                for строка in db.execute(
                    "SELECT id, вид, день, текст, вернуться FROM inbox"
                    " WHERE статус=? AND вернуться!='' AND вернуться<=? ORDER BY вернуться, id",
                    (ОТЛОЖЕНА, сегодня.isoformat()),
                )
            ]
