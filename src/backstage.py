@dataclass(frozen=True)
class Finding:
    """Что фоновая работа нашла и какой задачей это дёргает за рукав."""

    title: str        # ровно эта строка ищется в Todoist — она и есть опознавание
    why: str          # уходит в описание карточки при заведении
    due: str = "сегодня"
    агенту: str = ""  # готовое задание тому, кто правит код коуча; пусто — чинит человек
    размер: str = S   # сколько времени берёт у ЧЕЛОВЕКА, а не сколько идёт работа
    # ГДЕ ЭТО РАЗБИРАЮТ — пометка, а не догадка по месту карточки. Заведена
    # 13.08.2026 вместе с переездом всех находок под мастер-карточку: раньше
    # ответ на этот вопрос читался по тому, висит задача подзадачей или сама
    # по себе, и переезд стёр бы его вовсе. Умолчание — «код»: находка,
    # про которую забыли подумать, скорее техническая, и хуже принести
    # техническую беду в разговор с коучем, чем наоборот.
    разбор: str = КОД


# Половина находок чинится не человеком, а сессией Claude Code в папке
# с исходниками коуча. Человек не обязан пересказывать ей, что случилось:
# пересказ технической беды словами того, кто в ней не разбирается, — самая
# дорогая часть починки и первое место, где теряются подробности.
#
# Поэтому задача несёт **готовый текст**: скопировал целиком — отправил.
# Текст пишется здесь, рядом с находкой, а не в голове человека.
ШАПКА_АГЕНТУ = "──── Скопируй всё, что ниже, и отправь агенту, который правит код коуча ────"
ХВОСТ_АГЕНТУ = (
    "Цифры выше — находка той ночи, когда задача завелась. Если в задаче есть "
    "комментарии, добавь их тоже: это находки следующих ночей, и в описании их нет."
)


def описание(finding: "Finding", note: str) -> str:
    """Текст карточки: почему дёргаем, что нашли и что переслать агенту."""
    куски = [finding.why, note]
    if finding.агенту:
        куски.append(f"{ШАПКА_АГЕНТУ}\n\n{finding.агенту.strip()}\n\nНаходка: {note}\n\n"
                     f"{ХВОСТ_АГЕНТУ}")
    return "\n\n".join(к for к in куски if к)


