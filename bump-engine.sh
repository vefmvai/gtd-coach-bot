#!/bin/bash
# bump-engine.sh — поднять версию движка коуча самостоятельно, ночью, молча.
#
# Движок — это Claude Code, которым коуч думает. Он выходит почти каждый день,
# и до 30.08.2026 каждая новая версия заводила человеку задачу «подними руками».
# Задача, которая тридцать раз подряд просит сделать одно и то же, — это работа
# машины, отданная человеку: он открывал её каждое утро и нажимал одно и то же.
#
# Что осталось от прежнего порядка и почему. Версия по-прежнему ЗАПИНЕНА:
# сборка ставит названное число, а не «что там сегодня в npm». Инцидент
# 30.07.2026 (непиненная пересборка молча привезла другой мозг, коуч дважды
# ответил заглушкой) отменяет не пин, а ручной труд вокруг него. Менялось
# в подъёме только то, кто нажимает кнопку.
#
# Главное здесь — шаг 5. Зелёный контейнер НЕ доказывает, что коуч думает:
# 30.07 он был зелёным ровно в тот час, когда бот отвечал заглушкой. Поэтому
# приёмка — живой вопрос движку, а не healthcheck.
#
# Запускать НА СЕРВЕРЕ, кроном, от того же человека, что и update.sh:
#
#   ./bump-engine.sh
#
# Молчание — штатный исход. Человека дёргаем ровно в одном случае: новая версия
# не встала, мы откатились, и надо смотреть глазами.

set -euo pipefail

# ── 1. Где что лежит ─────────────────────────────────────────────────────────
BOT="${BOT_DIR:-$(cd "$(dirname "$0")" && pwd)}"
# Имя контейнера — из `.env` этой копии, тем же правилом, что в update.sh.
if [ -z "${CONTAINER_NAME:-}" ] && [ -f "$BOT/.env" ]; then
    CONTAINER_NAME=$(grep -m1 '^CONTAINER_NAME=' "$BOT/.env" | cut -d= -f2- || true)
fi
CONTAINER="${CONTAINER_NAME:-gtd-coach-bot}"
ARCHIVE_DIR="${BOT}-deploy-logs"

# Дом версии на боевом сервере. НЕ Dockerfile: тот приезжает с GitHub через
# `git pull --ff-only`, и правка на сервере сломала бы следующую выкатку.
# В Dockerfile остаётся версия, с которой начинает новая установка; здесь —
# та, что стоит на этом сервере сейчас. Читает файл `update.sh`, пишет — этот
# скрипт, и только после того, как версия принята живым вопросом.
VERSION_FILE="$ARCHIVE_DIR/движок-версия"

# Версия, которая уже не прошла приёмку. Без этой памяти ночь ломилась бы
# в сломанную версию каждую ночь: пересборка, два перезапуска коуча и новый
# комментарий к задаче — и так, пока npm не выпустит следующую. Выйдет
# следующая — попробуем её, эта запись про одно конкретное число.
REJECTED_FILE="$ARCHIVE_DIR/движок-отвергнут"

PACKAGE="@anthropic-ai/claude-code"
REGISTRY="https://registry.npmjs.org/$PACKAGE/latest"

# Сколько ждём. Первые два числа — как в update.sh; третье своё: живой вопрос
# движку идёт через сеть до Anthropic и обратно, минуты ему мало.
# Переопределяются окружением ради проверки: ветку отката иначе не пройти
# ни разу, а непроверенная ветка спасения — это ветка, которой нет.
HEALTH_TRIES="${HEALTH_TRIES:-30}"
HEALTH_SLEEP="${HEALTH_SLEEP:-5}"
ASK_TIMEOUT="${ASK_TIMEOUT:-180}"

сказать() { printf '%s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }

mkdir -p "$ARCHIVE_DIR"

# ── 2. Что стоит и что вышло ─────────────────────────────────────────────────
#
# Что стоит — спрашиваем у ОБРАЗА, а не у файла: файл говорит, что мы хотели,
# образ — что получилось. Расходятся они ровно в интересном случае (сборка
# не доехала), и верить надо образу.
running=$(docker exec "$CONTAINER" printenv CLAUDE_CODE_VERSION 2>/dev/null || true)
if [ -z "$running" ]; then
    сказать "контейнер не отвечает или не знает своей версии — подъём пропускаю"
    exit 0
fi

latest=$(curl -fsS --max-time 20 "$REGISTRY" 2>/dev/null | jq -r '.version // empty' || true)
if [ -z "$latest" ]; then
    сказать "npm не ответил — подъём пропускаю, попробуем завтра"
    exit 0
fi

if [ "$running" = "$latest" ]; then
    # Файл мог отстать от образа, если образ собирали руками. Выравниваем молча:
    # иначе следующая выкатка вернёт версию назад.
    [ "$(cat "$VERSION_FILE" 2>/dev/null || true)" = "$running" ] || echo "$running" > "$VERSION_FILE"
    сказать "движок свежий: $running"
    exit 0
fi

if [ "$(cat "$REJECTED_FILE" 2>/dev/null || true)" = "$latest" ]; then
    сказать "версия $latest уже не прошла приёмку — жду следующую, стоит $running"
    exit 0
fi

сказать "поднимаю движок: $running → $latest"

# ── 3. Собрать и поднять ─────────────────────────────────────────────────────
cd "$BOT"

# Sha вшивается в образ тем же приёмом, что в update.sh: иначе `/version`
# после подъёма скажет «сборка неизвестна». Клон здесь не тянется — тянет
# только update.sh, — поэтому sha берётся тот, что уже раскатан.
GIT_SHA=$(git -c "safe.directory=$BOT" -C "$BOT" rev-parse HEAD 2>/dev/null || echo "")
export GIT_SHA

собрать_и_поднять() {          # $1 — версия движка
    docker compose build --build-arg "CLAUDE_CODE_VERSION=$1" \
        && docker compose up -d
}

# Логи снимаем ДО подмены контейнера: `up -d` пересоздаёт его, и логи старого
# исчезают вместе с ним (та же беда, что поймана выкаткой 31.07.2026).
STAMP=$(date -u +%Y%m%dT%H%M%SZ)
docker logs "$CONTAINER" > "$ARCHIVE_DIR/$CONTAINER-движок-$STAMP.log" 2>&1 || true
ls -1t "$ARCHIVE_DIR/$CONTAINER"-движок-*.log 2>/dev/null | tail -n +11 | xargs -r rm -f

# ── 4. Приёмка ───────────────────────────────────────────────────────────────
здоров() {
    local status
    for _ in $(seq 1 "$HEALTH_TRIES"); do
        status=$(docker inspect -f '{{.State.Health.Status}}' "$CONTAINER" 2>/dev/null || echo "нет")
        [ "$status" = "healthy" ] && return 0
        sleep "$HEALTH_SLEEP"
    done
    return 1
}

думает() {
    # Живой вопрос движку. Спрашиваем самое дешёвое, что вообще бывает:
    # проверяем не ум, а то, что цепочка «движок → подписка → сеть → ответ»
    # цела. Мимо памяти и мимо разговора: сессию коуча этот вопрос не трогает.
    # Имя переменной латиницей, как и всюду в bash-скриптах продукта: кириллицу
    # он в именах не принимает, и `${ответ}` роняет скрипт прямо в приёмке —
    # то есть ровно там, где обязан сработать откат. Поймано прогоном 30.08.2026.
    local reply
    reply=$(timeout "$ASK_TIMEOUT" docker exec "$CONTAINER" \
        claude -p "Ответь одним словом: готов" 2>/dev/null || true)
    [ -n "${reply//[[:space:]]/}" ]
}

откат() {                      # $1 — куда возвращаемся, $2 — на чём споткнулись
    сказать "ВНИМАНИЕ: $2 — откатываюсь на $1"
    # Дом версии правим ДО сборки, а не после: если откат не доедет, в доме
    # обязана лежать та версия, которую мы считаем годной, — по ней соберёт
    # следующая выкатка. Оставить там непринятую значит отменить откат.
    echo "$1" > "$VERSION_FILE"
    echo "$latest" > "$REJECTED_FILE"
    if собрать_и_поднять "$1" && здоров; then
        сказать "откат удался: работает $1"
    else
        сказать "ВНИМАНИЕ: откат тоже не поднялся — контейнер лежит"
    fi
    беда "$1" "$2"
    exit 1
}

# Задачу заводит сам бот, его же кодом: у заведения задач один дом (backstage),
# второй завёл бы вторую карточку рядом с живой. Контейнер после отката лежит —
# задачи не будет; тогда о беде скажет хостовый сторож check-containers.sh,
# он шлёт алерт в телеграм каждые десять минут, пока красно.
беда() {                       # $1 — версия, на которой остались, $2 — что случилось
    docker exec -i "$CONTAINER" python3 - "$1" "$2" "$latest" <<'PY' 2>/dev/null || \
        сказать "задачу о беде завести не вышло — смотри алерт сторожа"
import asyncio, os, sys
sys.path.insert(0, "/app")
from pathlib import Path
from src.backstage import raise_task
from src.inbox import Inbox

осталось, беда, хотели = sys.argv[1], sys.argv[2], sys.argv[3]
полка = Inbox(Path(os.environ.get("ARCHIVE_DB", "/archive/coach.db")))
исход = asyncio.run(raise_task(
    os.environ["TODOIST_API_TOKEN"], "движок_не_встал",
    f"Ночью поднимал {осталось} → {хотели}: {беда}. Откатился, работает {осталось}.",
    inbox=полка,
))
print("задача:", исход or "не доехала до Todoist")
PY
}

if ! собрать_и_поднять "$latest"; then
    # Сборка не доехала — контейнер не тронут и работает на прежнем образе,
    # откатывать нечего. Но человеку сказать надо: молчание тут означало бы
    # «версия поднимается сама», а она не поднимается.
    сказать "ВНИМАНИЕ: сборка $latest не удалась, остаёмся на $running"
    беда "$running" "сборка не удалась"
    exit 1
fi

здоров  || откат "$running" "контейнер не стал healthy за $((HEALTH_TRIES * HEALTH_SLEEP)) секунд"
думает  || откат "$running" "движок не ответил на живой вопрос"

# ── 5. Принято ───────────────────────────────────────────────────────────────
echo "$latest" > "$VERSION_FILE"
rm -f "$REJECTED_FILE"
сказать "движок поднят и отвечает: $running → $latest"
exit 0
