#!/bin/bash
# update.sh — обновить GTD-коуча целиком.
#
# GTD-коуч это не один репозиторий, а продукт из четырёх: бот (эта папка),
# плагин с ролью и навыками, и два сервера инструментов. Обновлять их по
# отдельности — значит однажды получить свежего бота со старой ролью.
#
# Запускать НА СЕРВЕРЕ, в папке бота:
#
#   ./update.sh
#
# Что делает: тянет каждый клон с GitHub, пересобирает образ бота, если его код
# изменился, перезапускает контейнер, если изменилось смонтированное, и ждёт,
# пока он станет healthy. Чего не делает: не трогает мозг (это ваши данные)
# и не поднимает версию движка Claude Code — этим занят отдельный ночной
# скрипт bump-engine.sh. Но принятую им версию эта команда обязана сохранить,
# см. VERSION_FILE ниже.
#
# Не склонированную часть пропускает молча: ставить календарь необязательно.
#
# Пути можно переопределить окружением — но они обязаны совпадать с томами
# в docker-compose.yml, иначе обновится не то, что смонтировано. За этим
# следит тест tests/test_update_sh.py.
#
# Имена переменных и функций здесь латиницей, в отличие от питона: bash
# кириллицу в именах не принимает и падает синтаксической ошибкой.

set -euo pipefail

# ── 0. Работаем из копии ─────────────────────────────────────────────────────
#
# Этот скрипт лежит в том же репозитории, который сам же и тянет. Bash читает
# файл кусками по ходу выполнения, поэтому `git pull` посреди работы способен
# подменить ещё не прочитанный хвост — и выполнится половина старого скрипта,
# половина нового. Поэтому первым делом копируем себя во временный файл.
if [ "${FROM_COPY:-}" != "1" ]; then
    export BOT_DIR="${BOT_DIR:-$(cd "$(dirname "$0")" && pwd)}"
    tmp=$(mktemp)
    cat "$0" > "$tmp"
    FROM_COPY=1 exec bash "$tmp" "$@"
fi
trap 'rm -f "$0"' EXIT     # $0 здесь уже копия, а не сам скрипт

# ── 1. Где что лежит ─────────────────────────────────────────────────────────
BOT="${BOT_DIR:-$(pwd)}"
PLUGIN="${PLUGIN_DIR:-/opt/apps/gtd-coach-plugin}"
TODOIST="${TODOIST_DIR:-/opt/apps/todoist-mcp}"
GCAL="${GCAL_DIR:-/opt/apps/gcal-mcp}"
# Имя контейнера — из `.env` этой копии, как и у docker-compose.yml: вторая
# копия коуча на том же сервере живёт под своим именем. Нет строки — имя
# первой установки.
if [ -z "${CONTAINER_NAME:-}" ] && [ -f "$BOT/.env" ]; then
    CONTAINER_NAME=$(grep -m1 '^CONTAINER_NAME=' "$BOT/.env" | cut -d= -f2- || true)
fi
CONTAINER="${CONTAINER_NAME:-gtd-coach-bot}"

# Улики и отметки — рядом с папкой бота, а не внутри неё: `data/` принадлежит
# пользователю ВНУТРИ контейнера (uid 1000), и хозяин сервера писать туда
# не может. Поймано первой боевой выкаткой 31.07.2026.
ARCHIVE_DIR="${BOT}-deploy-logs"
STAMPS="$ARCHIVE_DIR/stamps"
mkdir -p "$STAMPS"

# Какой движок стоит на ЭТОМ сервере. Дом версии переехал сюда 30.08.2026,
# когда подъём стал ночным и автоматическим (bump-engine.sh): править Dockerfile
# на сервере нельзя, он приезжает с GitHub через `git pull --ff-only`.
# В Dockerfile осталась версия, с которой начинает НОВАЯ установка; здесь —
# та, что принята на этом сервере. Нет файла — собираем по Dockerfile, и это
# правильное поведение для того, кто поставил коуча вчера.
VERSION_FILE="$ARCHIVE_DIR/движок-версия"

REBUILD=0   # менялся код бота — нужна пересборка образа
RESTART=0   # менялось смонтированное (плагин, инструменты) — хватит перезапуска
CHANGES=()

# ── 2. Тянем ─────────────────────────────────────────────────────────────────
#
# Что раскатано, помним отметками — по одной на часть. Отметка ставится ТОЛЬКО
# после успешного подъёма контейнера.
#
# Раньше решение «пересобирать или нет» принималось по дельте pull: сдвинулся
# HEAD — раскатываем. Это врёт при любом обрыве посередине. 31.07.2026 первая же
# боевая выкатка подтянула код и упала на снятии логов; следующий прогон увидел
# «pull ничего не изменил», объявил «нечего раскатывать» и вышел с успехом —
# при живом контейнере на старом образе. Сервер молча остаётся позади навсегда,
# и скрипт при этом рапортует, что всё хорошо.
#
# Правильный вопрос — не «сдвинулся ли pull», а «совпадает ли раскатанное
# с тем, что в клоне».
# Без выравнивания по колонкам намеренно: `printf "%-14s"` считает БАЙТЫ,
# а имена частей русские — «бот» это шесть байт при трёх буквах, и колонка
# разъезжается. Поймано первым же прогоном на сервере.
pull_part() {                  # $1 — что за часть, $2 — путь, $3 — какой флаг
    local name="$1" dir="$2" flag="$3" head was line stamp
    if [ ! -d "$dir/.git" ]; then
        printf "  %s — не установлен, пропускаю\n" "$name"
        return 0
    fi
    git -C "$dir" pull --ff-only -q
    head=$(git -C "$dir" rev-parse HEAD)
    # Имя отметки — по имени папки, а не по русскому названию части: отметки
    # на сервере уже лежат от прежней выкатки, и переименование обнулило бы
    # их все разом — скрипт решил бы, что не раскатано ничего.
    stamp="$STAMPS/$(basename "$dir")"
    was=$(cat "$stamp" 2>/dev/null || echo "")
    if [ "$head" = "$was" ]; then
        printf "  %s — %s, уже стоит\n" "$name" "${head:0:7}"
        return 0
    fi
    if [ -z "$was" ]; then
        printf "  %s — %s, отметки нет, раскатываю\n" "$name" "${head:0:7}"
    else
        printf "  %s — %s → %s\n" "$name" "${was:0:7}" "${head:0:7}"
        # Что именно приехало. Без этого «обновлено» — слово без содержания,
        # а человек должен видеть, за что он платит перезапуском.
        while IFS= read -r line; do
            [ -n "$line" ] && CHANGES+=("  $name: $line")
        done < <(git -C "$dir" log --oneline --no-decorate "$was..$head" 2>/dev/null | head -5)
    fi
    eval "$flag=1"
}

echo "Тяну части GTD-коуча:"
pull_part бот          "$BOT"     REBUILD
pull_part плагин       "$PLUGIN"  RESTART
pull_part todoist-mcp  "$TODOIST" RESTART
pull_part gcal-mcp     "$GCAL"    RESTART

if [ "$REBUILD" = "0" ] && [ "$RESTART" = "0" ]; then
    echo
    echo "Всё уже свежее — раскатывать нечего."
    exit 0
fi

# ── 3. Улики до перезапуска ──────────────────────────────────────────────────
#
# Логи снимаем ДО перезапуска. `up --build` пересоздаёт контейнер, и логи
# старого исчезают вместе с ним. 31.07.2026 из-за этого не удалось разобрать,
# почему коуч не ответил на утренний чек-ин: улики уничтожила сама выкатка.
cd "$BOT"
STAMP=$(date -u +%Y%m%dT%H%M%SZ)
docker logs "$CONTAINER" > "$ARCHIVE_DIR/$CONTAINER-$STAMP.log" 2>&1 || true
echo
echo "[улики] логи до перезапуска: $ARCHIVE_DIR/$CONTAINER-$STAMP.log"
# Держим последние 20 снимков — этого хватает на пару недель обновлений.
ls -1t "$ARCHIVE_DIR/$CONTAINER"-*.log 2>/dev/null | tail -n +21 | xargs -r rm -f

# ── 4. Раскатываем ───────────────────────────────────────────────────────────
if [ "$REBUILD" = "1" ]; then
    # Sha вшивается в образ: изнутри контейнера узнать версию своего кода
    # больше неоткуда — `.git` рядом с кодом нет, он остаётся в клоне.
    GIT_SHA=$(git -C "$BOT" rev-parse HEAD)
    export GIT_SHA
    echo "[сборка] пересобираю образ бота на ${GIT_SHA:0:7}"
    # Версия движка — из дома, а не из Dockerfile. Без этой строки выкатка кода
    # молча вернула бы движок на ту версию, с которой начинали: ночной подъём
    # поставил бы её обратно следующей ночью, но день коуч прожил бы на старой.
    ENGINE=$(cat "$VERSION_FILE" 2>/dev/null || true)
    if [ -n "$ENGINE" ]; then
        echo "[сборка] движок $ENGINE (принят ночным подъёмом)"
        docker compose build --build-arg "CLAUDE_CODE_VERSION=$ENGINE"
        docker compose up -d
    else
        docker compose up -d --build
    fi
else
    # Плагин и серверы инструментов смонтированы, а не вшиты в образ. Но движок
    # читает плагин при старте сессии, поэтому одного монтирования мало — рестарт.
    echo "[перезапуск] смонтированное изменилось"
    docker compose restart
fi

# ── 5. Проверяем ─────────────────────────────────────────────────────────────
echo "[проверка] жду, пока контейнер станет healthy…"
for _ in $(seq 1 30); do
    status=$(docker inspect -f '{{.State.Health.Status}}' "$CONTAINER" 2>/dev/null || echo "нет")
    if [ "$status" = "healthy" ]; then
        for dir in "$BOT" "$PLUGIN" "$TODOIST" "$GCAL"; do
            [ -d "$dir/.git" ] || continue
            git -C "$dir" rev-parse HEAD > "$STAMPS/$(basename "$dir")"
        done
        echo "[готово] контейнер healthy"
        if [ ${#CHANGES[@]} -gt 0 ]; then
            echo
            echo "Что изменилось:"
            printf "%s\n" "${CHANGES[@]}"
        fi
        echo
        echo "Проверь вживую: напиши боту /version в телеграме."
        exit 0
    fi
    sleep 5
done

echo "[ВНИМАНИЕ] контейнер не стал healthy за 150 секунд — смотри docker logs $CONTAINER" >&2
exit 1
