"""Сторож: в публичном репозитории не должно быть личного.

**Почему тест, а не память.** Обезличивание — разовая работа, а репозиторий
живёт дальше: следующая правка допишет «спроси у Тани» в комментарий, и никто
этого не заметит до момента, когда файл уже лежит на GitHub. Правило без
прибора не выполняется — это самая дорогая находка проекта.

**Почему копия в каждом репозитории.** Тест обязан работать, когда репозиторий
клонировали одного, без соседей. Дотянуться до общего списка неоткуда, значит
список дублируется осознанно: четыре репозитория — четыре копии. Правишь
список — правь во всех четырёх (`grep -rl ЗАПРЕЩЁННЫЕ ..`).
"""

from __future__ import annotations

from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]

# Ищется в нижнем регистре, поэтому корни короткие: «васил» ловит и «Василий»,
# и «Василия», и «василия».
ЗАПРЕЩЁННЫЕ = (
    "васил", "vasili", "efimov", "efimoff",
    "мастерск", "лаборатор",
    "bronto", "vefmv_gtd_bot",
    "нейроакадем", "academii",
    # Домашний каталог мака: именно с именем, иначе ловится путь Google API
    # «/users/me/calendarList» — ложная тревога, от которой сторож перестают читать.
    "/users/vasil",
    # География, банки и счета владельца. Добавлено 08.08.2026 приёмкой этапа 23:
    # прогон от лица ученика на свежем клоне нашёл «секция Сделать перед Бали»
    # в публичной методологии, а сторож промолчал — этих слов он не знал.
    # Владелец сказал прямо: «плагин в открытом репо должен быть без какой бы
    # то ни было привязки ко мне».
    #
    # «бали» пишется с пробелом впереди намеренно: без него ловится
    # «глобализация», и сторож, который кричит на обычное слово, читать
    # перестают. Ценой этого сторож не увидит «Бали» в начале строки —
    # размен принят осознанно, потому что ложная тревога дороже.
    " бали", "брылин", "тинькоф", "permata", "telkomsel", "убрир",
    "dotupractic",
    # Второй человек с 05.10.2026 — у него своя копия коуча и общий проект
    # с владельцем (этап 26). Его имя и адреса — то же личное.
    "татьян", "tefmv", "pivnev",
)

# Папки, которые не наши: чужой код, кэши, история git.
ПРОПУСКАЕМ = {".git", ".venv", "venv", "__pycache__", ".pytest_cache", "node_modules",
              ".mypy_cache", ".ruff_cache"}

ДВОИЧНЫЕ = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".db", ".sqlite",
            ".woff", ".woff2", ".zip", ".gz", ".ogg", ".oga", ".mp3"}

# Единственное исключение, и оно про данные, а не про текст: роль человека
# в архиве до 02.08.2026 звалась именем владельца. Строка миграции обязана
# знать старое значение — иначе живая база молча потеряет связь с прошлым.
# Исключение точечное: файл плюс подстрока, а не «этот файл не проверяем».
ИСКЛЮЧЕНИЯ = {
    "src/archive.py": ("role='vasiliy'",),
    "tests/test_архив_миграция.py": ("vasiliy",),
    "tests/test_archive_migration.py": ("vasiliy",),
}


def файлы():
    """Все текстовые файлы репозитория, кроме самого сторожа.

    Себя сторож не проверяет по очевидной причине: список запрещённых слов
    в нём написан целиком, и иначе он краснел бы всегда. Цена исключения —
    единственный файл, в котором личное может спрятаться; она принята
    сознательно, потому что список должен читаться глазами, а не собираться
    из кусков ради того, чтобы обмануть собственный обход.
    """
    сам = Path(__file__).resolve()
    for путь in КОРЕНЬ.rglob("*"):
        if not путь.is_file() or путь.resolve() == сам:
            continue
        if ПРОПУСКАЕМ & set(путь.relative_to(КОРЕНЬ).parts):
            continue
        if путь.suffix.lower() in ДВОИЧНЫЕ:
            continue
        yield путь


def test_личного_в_репозитории_нет():
    находки: list[str] = []
    for путь in файлы():
        отн = путь.relative_to(КОРЕНЬ).as_posix()
        try:
            текст = путь.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        разрешено = ИСКЛЮЧЕНИЯ.get(отн, ())
        for номер, строка in enumerate(текст.splitlines(), 1):
            низ = строка.lower()
            if any(о.lower() in низ for о in разрешено):
                continue
            for слово in ЗАПРЕЩЁННЫЕ:
                if слово in низ:
                    находки.append(f"{отн}:{номер}: «{слово}» в строке: {строка.strip()[:100]}")
    assert not находки, "личное просочилось в публичный репозиторий:\n" + "\n".join(находки)


def test_сторож_умеет_краснеть(tmp_path, monkeypatch):
    """Проверка сторожа нарочной поломкой: без неё зелёный тест ничего не значит.

    Ровно тот случай, когда «тест проходит» и «тест работает» — разные вещи:
    ошибка в обходе файлов дала бы вечно зелёный сторож.
    """
    import sys
    подделка = tmp_path / "гнездо"
    подделка.mkdir()
    (подделка / "заметка.md").write_text("спроси у Василия", encoding="utf-8")

    модуль = sys.modules[__name__]
    monkeypatch.setattr(модуль, "КОРЕНЬ", подделка)
    try:
        test_личного_в_репозитории_нет()
    except AssertionError as err:
        assert "васил" in str(err)
    else:
        raise AssertionError("сторож не заметил подложенное имя — он сломан")
