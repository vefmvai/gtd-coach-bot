@pytest.mark.parametrize("скрипт", ["update.sh", "bump-engine.sh"])
def test_имена_переменных_в_скриптах_латиницей(тексты, скрипт):
    """Bash кириллицу в именах переменных не принимает, и падает он не при

    разборе, а при выполнении: `bash -n` такую строку пропускает. 30.08.2026
    из-за `local ответ` приёмка подъёма умерла на месте — вместе с откатом,
    который обязан был сработать. Проверка глазами это уже пропустила однажды.
    """
    плохие = re.findall(r"^\s*(?:local\s+|export\s+)?([а-яёА-ЯЁ_][а-яёА-ЯЁ\w]*)=",
                        тексты[скрипт], re.M)
    плохие += re.findall(r"^\s*local\s+([а-яёА-ЯЁ][а-яёА-ЯЁ\w]*)\s*$", тексты[скрипт], re.M)
    assert not плохие, f"кириллица в имени переменной: {плохие}"


def test_откат_переписывает_дом_версии(тексты):
    """Откатились, а в доме осталась непринятая версия — и следующая выкатка

    соберёт с ней, отменив откат молча. Поймано боевой проверкой 30.08.2026:
    контейнер честно вернулся на 2.1.243, а дом показывал 2.1.251."""
    подъём = тексты["bump-engine.sh"]
    откат = подъём[подъём.index("откат() {"):подъём.index("беда() {")]
    assert 'echo "$1" > "$VERSION_FILE"' in откат, "откат не поправил дом версии"


def test_отвергнутая_версия_второй_раз_не_пробуется(тексты):
    """Сломанная версия висит в npm днями. Без памяти об отказе каждая ночь

    ломала бы коуча заново: пересборка, два перезапуска и новый комментарий."""
    подъём = тексты["bump-engine.sh"]
    assert 'REJECTED_FILE=' in подъём, "памяти об отказе нет"
    пропуск = подъём.index('уже не прошла приёмку')
    подъём_версии = подъём.index('сказать "поднимаю движок')
    assert пропуск < подъём_версии, "проверка отказа стоит после подъёма — она бесполезна"
